#!/usr/bin/env node
// Generates lib/world-paths.generated.ts from world-atlas topojson, projected
// once at build time so the runtime bundle has no geo dependencies.
//
// Run with: node scripts/generate-world-paths.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { geoNaturalEarth1, geoPath } from "d3-geo";
import { feature } from "topojson-client";
import topology from "world-atlas/countries-110m.json" with { type: "json" };

const __dirname = dirname(fileURLToPath(import.meta.url));
const out = resolve(__dirname, "../lib/world-paths.generated.ts");

const WIDTH = 980;
const HEIGHT = 480;

const collection = feature(topology, topology.objects.countries);
const projection = geoNaturalEarth1().fitSize([WIDTH, HEIGHT], collection);
const path = geoPath(projection);

const round = (d) =>
  d.replace(/-?\d+\.\d+/g, (m) => Number.parseFloat(m).toFixed(1));

const countries = collection.features
  .map((f) => {
    const d = path(f);
    if (!d) return null;
    return {
      id: String(f.id ?? f.properties.name),
      name: f.properties.name,
      d: round(d),
    };
  })
  .filter(Boolean)
  .sort((a, b) => a.name.localeCompare(b.name));

const ts = `// AUTO-GENERATED by scripts/generate-world-paths.mjs - do not edit by hand.
// Source: world-atlas countries-110m.json, projected with d3-geo geoNaturalEarth1.

export type CountryPath = { id: string; name: string; d: string };

export const WORLD_VIEWBOX = { width: ${WIDTH}, height: ${HEIGHT} } as const;

export const COUNTRY_PATHS: readonly CountryPath[] = ${JSON.stringify(countries, null, 2)} as const;
`;

writeFileSync(out, ts);
console.log(`wrote ${out} (${countries.length} countries, ${ts.length} bytes)`);
